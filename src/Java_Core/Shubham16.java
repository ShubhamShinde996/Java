package Java_Core;
// 21 .  While loops in Java
public class Shubham16 {
    public static void main(String[] args) {
        // 1.while loop
        System.out.println("Using Loops : ");
        int a = 1 ;
         while (a<=3){
             System.out.println(a);
             a++;
         }
        System.out.println("Finish Running While Loops!");

         // 2 . infinite loop using for while loops
        while(true){
            System.out.println("I am an infinite while loop!");
        }
    }
}
