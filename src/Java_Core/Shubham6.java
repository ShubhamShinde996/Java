package Java_Core;
// chapter 2
// 8.Operators , Types of Operator & Expressions
public class Shubham6 {
    public static void main(String[] args) {
        // method 1
        // arithmetic operator
        int a = 4;
        int b = 6;
        System.out.println(a+b);

        // method 2
        // modulo operator %
        double c = 3 % 10.54d;
        System.out.println(c);

        // Assignment operator
        int x = 9;
        x*=3;
        System.out.println(x);

        // comparisons Operator
        System.out.println(7>=8);

        // logical operator
        System.out.println(64>5 && 64>98);
        System.out.println(64>5 || 64>98);

       // Bitwise operator
        System.out.println(2&3);


    }
}
