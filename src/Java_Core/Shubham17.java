public class Shubham17 {
    public static void main(String[] args) {
        // Do - While
        int i=0;
        while(i<5){
            System.out.println(i);
            i++;
        }

        // 2 . do-while loops
        System.out.println("It's Do while loop : - ");
        int b = 10;
        do{
            System.out.println(i);
            b++;
        }while(b<5);


        // print the natural numbers in using do while loops
        System.out.println("Natural Numbers : - ");
        int c = 1;
        do{
            System.out.println(c);
            c++;
        }while(c<=45);
    }
}
